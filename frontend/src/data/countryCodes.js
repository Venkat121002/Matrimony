/**
 * Map country name or citizenship to default calling code
 */
export const getCallingCodeForCountry = (countryName) => {
  if (!countryName) return '+65';
  const norm = String(countryName).trim().toLowerCase();

  if (norm.includes('singapore') || norm.includes('சிங்கப்பூர்')) return '+65';
  if (norm.includes('uae') || norm.includes('dubai') || norm.includes('emirates') || norm.includes('துபாய்') || norm.includes('அமீரகம்')) return '+971';
  if (norm.includes('malaysia') || norm.includes('மலேசியா')) return '+60';
  if (norm.includes('saudi') || norm.includes('சவுதி')) return '+966';
  if (norm.includes('qatar') || norm.includes('கத்தார்')) return '+974';
  if (norm.includes('kuwait') || norm.includes('குவைத்')) return '+965';
  if (norm.includes('oman') || norm.includes('ஓமன்')) return '+968';
  if (norm.includes('bahrain') || norm.includes('பஹ்ரைன்')) return '+973';
  if (norm.includes('uk') || norm.includes('united kingdom') || norm.includes('england') || norm.includes('london') || norm.includes('இங்கிலாந்து')) return '+44';
  if (norm.includes('usa') || norm.includes('united states') || norm.includes('america') || norm.includes('அமெரிக்கா')) return '+1';
  if (norm.includes('canada') || norm.includes('கனடா')) return '+1';
  if (norm.includes('australia') || norm.includes('ஆஸ்திரேலியா')) return '+61';
  if (norm.includes('new zealand') || norm.includes('நியூசிலாந்து')) return '+64';
  if (norm.includes('sri lanka') || norm.includes('ceylon') || norm.includes('இலங்கை')) return '+94';
  if (norm.includes('brunei')) return '+673';
  if (norm.includes('maldives')) return '+960';
  if (norm.includes('france')) return '+33';
  if (norm.includes('germany')) return '+49';
  if (norm.includes('ireland')) return '+353';
  if (norm.includes('switzerland')) return '+41';
  if (norm.includes('netherlands')) return '+31';
  if (norm.includes('india') || norm.includes('இந்தியா')) return '+91';

  const match = COUNTRY_CALLING_CODES.find(
    (c) => c.name.toLowerCase().includes(norm) || c.code.toLowerCase() === norm
  );
  return match ? match.dialCode : '+65';
};

/**
 * Get country object by dial code
 */
export const getCountryByDialCode = (dialCode) => {
  if (!dialCode) return COUNTRY_CALLING_CODES[0];
  const cleaned = dialCode.startsWith('+') ? dialCode : `+${dialCode}`;
  return COUNTRY_CALLING_CODES.find((c) => c.dialCode === cleaned) || COUNTRY_CALLING_CODES[0];
};
